#!/usr/bin/env node
// Writes src/app/forms-signal/index.ts to point at the Signal Forms page
// when the installed Angular major supports it (>= 21), or at the
// fallback page on Angular 20. The route lazily loads this barrel, so
// the Signal Forms component is only compiled where it can compile.

import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "..", "package.json"));
const { version } = require("@angular/core/package.json");
const major = Number(version.split(".")[0]);

const target = major >= 21 ? "./signal-forms" : "./fallback";
const banner =
  "// GENERATED by scripts/sync-signal-forms.mjs - do not edit.\n" +
  `// Installed Angular major: ${major}.\n`;

writeFileSync(
  join(here, "..", "src", "app", "forms-signal", "index.ts"),
  `${banner}export { SignalFormsPage } from "${target}";\n`,
);
console.log(`forms-signal barrel -> ${target} (Angular ${version})`);
