// src/scripts/cem-angular-plugin.mjs
//
// Generates the @nysds/angular package sources (packages/angular/src) from the
// custom-elements manifest. Runs as part of `npm run cem`.
//
// Every custom element gets a thin standalone Angular component whose selector
// IS the custom-element tag. The wrapper exists for three reasons:
//
//   1. Registration — importing the wrapper side-effect-imports the element's
//      own module (`@nysds/nys-accordion/nys-accordionitem`), so consumers
//      never call `customElements.define` or add extra entry imports.
//   2. Property binding — Angular binds `[foo]` to a *directive* input, not to
//      the DOM element, whenever a directive on that element declares the
//      input. The wrapper therefore proxies every input straight through to
//      the underlying element via prototype getters/setters (see
//      `proxyInputs` in lib/utils.ts). Inputs are typed against the real
//      element class (`Pick<NysAccordionElement, ...>`), so `[expanded]="42"`
//      is a template type error.
//   3. Framework integration — `(nys-change)`-style outputs are proxied from
//      the element's CustomEvents, and form controls implement
//      ControlValueAccessor so `[(ngModel)]` / `formControlName` work.
//
// The generator also keeps packages/angular/package.json `dependencies` in
// sync with the component packages, so installing @nysds/angular pulls in
// every element implementation.

import fs from "fs";
import path from "path";

/**
 * Form components that implement ControlValueAccessor.
 *
 * `changeEvent` MUST be the event the element actually fires when its value
 * changes (this differs per component: text-like inputs fire `nys-input`,
 * discrete controls fire `nys-change` — see each component's CEM events).
 *
 * kind:
 *  - "value":   control with a string `value` property (text, select, ...)
 *  - "checked": boolean control (checkbox, toggle) — ngModel holds a boolean
 *  - "radio":   radio button — ngModel holds the *value* of the selected
 *               radio, so checked-ness is derived by comparing values
 */
const FORM_COMPONENTS = {
  "nys-textinput": { kind: "value", changeEvent: "nys-input", blurEvent: "nys-blur" },
  "nys-textarea": { kind: "value", changeEvent: "nys-input", blurEvent: "nys-blur" },
  "nys-datepicker": { kind: "value", changeEvent: "nys-input", blurEvent: "nys-blur" },
  "nys-select": { kind: "value", changeEvent: "nys-change", blurEvent: "nys-blur" },
  "nys-combobox": { kind: "value", changeEvent: "nys-change", blurEvent: "nys-blur" },
  "nys-fileinput": { kind: "value", changeEvent: "nys-change", blurEvent: "nys-blur" },
  "nys-checkbox": { kind: "checked", changeEvent: "nys-change", blurEvent: "nys-blur" },
  "nys-toggle": { kind: "checked", changeEvent: "nys-change", blurEvent: "nys-blur" },
  "nys-radiobutton": { kind: "radio", changeEvent: "nys-change", blurEvent: "nys-blur" },
};

const HEADER = `/* AUTO-GENERATED by src/scripts/cem-angular-plugin.mjs — do not edit.
 * Regenerate with \`npm run cem\`. */
`;

const UTILS = `${HEADER}
import { fromEvent } from "rxjs";

/**
 * Defines each input as a getter/setter pair on the wrapper component's
 * prototype that reads/writes the underlying custom element's property.
 *
 * Why: when an Angular component is attached to an element, template bindings
 * like \`[expanded]="true"\` set the *component's* property — the DOM element
 * never sees the value. These accessors forward every write to
 * \`this.el\` (the host custom element) so the Lit component reacts, and
 * every read reflects the element's live state.
 *
 * Writes run outside Angular's zone: setting a Lit reactive property
 * schedules an async re-render inside the element, which Angular's change
 * detection has no interest in.
 */
export const proxyInputs = (componentClass: any, inputs: string[]): void => {
  const prototype = componentClass.prototype;
  inputs.forEach((name) => {
    Object.defineProperty(prototype, name, {
      get() {
        return this.el[name];
      },
      set(value: any) {
        this.z.runOutsideAngular(() => (this.el[name] = value));
      },
      configurable: true,
    });
  });
};

/**
 * Exposes the element's CustomEvents as Angular-bindable outputs.
 *
 * Assigning \`fromEvent(el, "nys-change")\` to the component property named
 * "nys-change" makes \`(nys-change)="handler($event)"\` work: Angular
 * subscribes to whatever Subscribable it finds on the declared output
 * property, and the handler receives the original CustomEvent (detail
 * included). Listening happens on the element itself, so nothing is lost
 * to shadow-DOM retargeting.
 */
export const proxyOutputs = (instance: any, el: HTMLElement, events: string[]): void => {
  events.forEach((eventName) => (instance[eventName] = fromEvent(el, eventName)));
};

/**
 * Class decorator that wires up \`proxyInputs\` once per component class
 * (prototype accessors only need to be defined once, not per instance).
 */
export function ProxyCmp(opts: { inputs?: string[] }) {
  return (componentClass: any) => {
    if (opts.inputs?.length) {
      proxyInputs(componentClass, opts.inputs);
    }
    return componentClass;
  };
}
`;

function pascalToFileBase(modPath) {
  return path.basename(modPath).replace(/\.ts$/, "");
}

/** Public reactive properties → Angular inputs. */
function publicFields(decl) {
  return (decl.members ?? []).filter(
    (m) =>
      m.kind === "field" &&
      !m.static &&
      (m.privacy === undefined || m.privacy === "public") &&
      !m.name.startsWith("_"),
  );
}

function buildComponent({ decl, importPath, formConfig }) {
  const className = `${decl.name}Component`;
  const elementAlias = `${decl.name}Element`;
  const tagName = decl.tagName;

  const inputs = publicFields(decl).map((m) => m.name).sort();
  const events = [...new Set((decl.events ?? []).map((e) => e.name))].sort();

  const coreImports = ["ChangeDetectionStrategy", "Component", "ElementRef", "NgZone"];
  if (formConfig) coreImports.push("HostListener", "forwardRef");

  const utilImports = ["ProxyCmp"];
  if (events.length) utilImports.push("proxyOutputs");

  const inputsList = inputs.map((i) => JSON.stringify(i)).join(", ");
  const eventsList = events.map((e) => JSON.stringify(e)).join(", ");

  const lines = [];
  lines.push(HEADER);
  lines.push(`import { ${coreImports.sort().join(", ")} } from "@angular/core";`);
  if (formConfig) {
    lines.push(`import { NG_VALUE_ACCESSOR } from "@angular/forms";`);
    lines.push(`import type { ControlValueAccessor } from "@angular/forms";`);
  }
  if (events.length) {
    lines.push(`import type { Observable } from "rxjs";`);
  }
  lines.push(`import { ${utilImports.join(", ")} } from "./utils";`);
  lines.push(`import type { ${decl.name} as ${elementAlias} } from "${importPath}";`);
  lines.push(`import "${importPath}";`);
  lines.push("");

  lines.push(`@ProxyCmp({ inputs: [${inputsList}] })`);
  lines.push(`@Component({`);
  lines.push(`  selector: "${tagName}",`);
  lines.push(`  template: "<ng-content></ng-content>",`);
  lines.push(`  standalone: true,`);
  lines.push(`  changeDetection: ChangeDetectionStrategy.OnPush,`);
  lines.push(`  inputs: [${inputsList}],`);
  if (events.length) {
    lines.push(`  outputs: [${eventsList}],`);
  }
  if (formConfig) {
    lines.push(`  providers: [`);
    lines.push(`    {`);
    lines.push(`      provide: NG_VALUE_ACCESSOR,`);
    lines.push(`      useExisting: forwardRef(() => ${className}),`);
    lines.push(`      multi: true,`);
    lines.push(`    },`);
    lines.push(`  ],`);
  }
  lines.push(`})`);
  lines.push(`export class ${className}${formConfig ? " implements ControlValueAccessor" : ""} {`);
  lines.push(`  protected readonly el: ${elementAlias};`);
  lines.push("");
  lines.push(`  constructor(`);
  lines.push(`    elementRef: ElementRef,`);
  lines.push(`    protected readonly z: NgZone,`);
  lines.push(`  ) {`);
  lines.push(`    this.el = elementRef.nativeElement;`);
  if (events.length) {
    lines.push(`    proxyOutputs(this, this.el, [${eventsList}]);`);
  }
  lines.push(`  }`);

  if (formConfig) {
    lines.push("");
    lines.push(`  // ControlValueAccessor — bridges Angular forms (ngModel / formControlName)`);
    lines.push(`  // to the element's ${formConfig.kind === "checked" ? "\`checked\`" : formConfig.kind === "radio" ? "\`checked\`/\`value\`" : "\`value\`"} property and its \`${formConfig.changeEvent}\` event.`);
    lines.push(`  private onChange: (value: any) => void = () => {};`);
    lines.push(`  private onTouched: () => void = () => {};`);
    lines.push("");
    if (formConfig.kind === "checked") {
      lines.push(`  writeValue(value: any): void {`);
      lines.push(`    this.el.checked = !!value;`);
      lines.push(`  }`);
    } else if (formConfig.kind === "radio") {
      lines.push(`  // ngModel on a radio holds the selected radio's *value*; each radio is`);
      lines.push(`  // checked exactly when the model matches its own value (mirrors Angular's`);
      lines.push(`  // native RadioControlValueAccessor).`);
      lines.push(`  writeValue(value: any): void {`);
      lines.push(`    this.el.checked = value === this.el.value;`);
      lines.push(`  }`);
    } else {
      lines.push(`  writeValue(value: any): void {`);
      lines.push(`    this.el.value = value ?? "";`);
      lines.push(`  }`);
    }
    lines.push("");
    lines.push(`  registerOnChange(fn: (value: any) => void): void {`);
    lines.push(`    this.onChange = fn;`);
    lines.push(`  }`);
    lines.push("");
    lines.push(`  registerOnTouched(fn: () => void): void {`);
    lines.push(`    this.onTouched = fn;`);
    lines.push(`  }`);
    lines.push("");
    lines.push(`  setDisabledState(isDisabled: boolean): void {`);
    lines.push(`    this.el.disabled = isDisabled;`);
    lines.push(`  }`);
    lines.push("");
    lines.push(`  @HostListener("${formConfig.changeEvent}")`);
    lines.push(`  protected handleChangeEvent(): void {`);
    if (formConfig.kind === "checked") {
      lines.push(`    this.onChange(this.el.checked);`);
    } else if (formConfig.kind === "radio") {
      lines.push(`    if (this.el.checked) {`);
      lines.push(`      this.onChange(this.el.value);`);
      lines.push(`    }`);
    } else {
      lines.push(`    this.onChange(this.el.value);`);
    }
    lines.push(`  }`);
    lines.push("");
    lines.push(`  @HostListener("${formConfig.blurEvent}")`);
    lines.push(`  protected handleBlurEvent(): void {`);
    lines.push(`    this.onTouched();`);
    lines.push(`  }`);
  }

  lines.push(`}`);
  lines.push("");

  // Declaration merging: gives the component instance the element's own
  // property types (inputs) and typed Observables for each output, without
  // shipping runtime fields that would shadow the prototype accessors.
  const interfaceMembers = [];
  if (!events.length) {
    lines.push(`// eslint-disable-next-line @typescript-eslint/no-empty-object-type`);
  }
  const pickType = inputs.length
    ? `Pick<${elementAlias}, ${inputs.map((i) => JSON.stringify(i)).join(" | ")}>`
    : null;
  for (const e of events) {
    interfaceMembers.push(`  ${JSON.stringify(e)}: Observable<CustomEvent>;`);
  }
  lines.push(
    `export declare interface ${className}${pickType ? ` extends ${pickType}` : ""} {${
      interfaceMembers.length ? `\n${interfaceMembers.join("\n")}\n` : ""
    }}`,
  );
  lines.push("");

  return { className, tagName, content: lines.join("\n") };
}

export function angularWrapperPlugin(options = {}) {
  const outdir = path.resolve(process.cwd(), options.outdir || "./packages/angular");
  const srcdir = path.join(outdir, "src");
  const libdir = path.join(srcdir, "lib");
  const packagesDir = path.resolve(process.cwd(), "./packages");

  return {
    name: "nysds-angular-generator",
    packageLinkPhase({ customElementsManifest }) {
      fs.mkdirSync(libdir, { recursive: true });

      // Remove stale generated components so renamed/deleted elements don't linger.
      for (const f of fs.readdirSync(libdir)) {
        if (f.endsWith(".component.ts")) fs.rmSync(path.join(libdir, f));
      }

      const generated = [];
      const usedPackages = new Set();

      for (const mod of customElementsManifest.modules) {
        if (!mod.declarations) continue;

        // e.g. "packages/nys-accordion/src/nys-accordionitem.ts"
        const pathParts = mod.path.split("/");
        const packageFolder = pathParts[1];
        const fileBase = pascalToFileBase(mod.path);

        for (const decl of mod.declarations) {
          if (!decl.customElement || !decl.tagName) continue;

          // Every element (including child components) is imported from the package root,
          // as each package exports all of its sub-components from its root index.
          const importPath = `@nysds/${packageFolder}`;

          const { className, tagName, content } = buildComponent({
            decl,
            importPath,
            formConfig: FORM_COMPONENTS[decl.tagName],
          });

          fs.writeFileSync(path.join(libdir, `${tagName}.component.ts`), content, "utf-8");
          generated.push({ className, tagName });
          usedPackages.add(packageFolder);
        }
      }

      generated.sort((a, b) => a.tagName.localeCompare(b.tagName));

      // Shared proxy helpers.
      fs.writeFileSync(path.join(libdir, "utils.ts"), UTILS, "utf-8");

      // Convenience aggregate: `imports: [...NYSDS_COMPONENTS]` pulls in every wrapper.
      const aggregate = [
        HEADER,
        ...generated.map((c) => `import { ${c.className} } from "./${c.tagName}.component";`),
        "",
        `/** Every NYSDS wrapper component — spread into a standalone component's \`imports\`. */`,
        `export const NYSDS_COMPONENTS = [`,
        ...generated.map((c) => `  ${c.className},`),
        `] as const;`,
        "",
      ].join("\n");
      fs.writeFileSync(path.join(libdir, "nysds-components.ts"), aggregate, "utf-8");

      // ng-packagr entry point.
      const publicApi = [
        HEADER,
        ...generated.map((c) => `export * from "./lib/${c.tagName}.component";`),
        `export * from "./lib/nysds-components";`,
        `export { proxyInputs, proxyOutputs, ProxyCmp } from "./lib/utils";`,
        "",
      ].join("\n");
      fs.writeFileSync(path.join(srcdir, "public-api.ts"), publicApi, "utf-8");

      // Keep @nysds/angular's dependencies in sync with the component packages
      // it imports, so installing the wrapper package installs the elements.
      const pkgJsonPath = path.join(outdir, "package.json");
      if (fs.existsSync(pkgJsonPath)) {
        const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, "utf-8"));
        const deps = {};
        for (const folder of [...usedPackages].sort()) {
          const depPkgPath = path.join(packagesDir, folder, "package.json");
          const version = JSON.parse(fs.readFileSync(depPkgPath, "utf-8")).version;
          deps[`@nysds/${folder}`] = `^${version}`;
        }
        pkg.dependencies = deps;
        fs.writeFileSync(pkgJsonPath, JSON.stringify(pkg, null, 2) + "\n", "utf-8");
      }

      console.log("✅ Angular standalone components successfully written to " + libdir);
    },
  };
}
